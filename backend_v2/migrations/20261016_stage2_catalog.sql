CREATE TABLE IF NOT EXISTS public.cpa_networks (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name TEXT NOT NULL UNIQUE, website TEXT, description TEXT NOT NULL DEFAULT '',
 is_active BOOLEAN NOT NULL DEFAULT true, connection_notes TEXT NOT NULL DEFAULT '',
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.cpa_verticals (
 slug VARCHAR(80) PRIMARY KEY, title VARCHAR(120) NOT NULL,
 description TEXT NOT NULL DEFAULT '', icon_name VARCHAR(30) NOT NULL DEFAULT 'layers',
 display_order INTEGER NOT NULL DEFAULT 0, is_active BOOLEAN NOT NULL DEFAULT false,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
ALTER TABLE public.offers ADD COLUMN IF NOT EXISTS vertical_slug VARCHAR(80) REFERENCES public.cpa_verticals(slug);
ALTER TABLE public.offers ADD COLUMN IF NOT EXISTS network_id BIGINT REFERENCES public.cpa_networks(id);
ALTER TABLE public.offers ADD COLUMN IF NOT EXISTS offer_type VARCHAR(20) NOT NULL DEFAULT 'offer';
ALTER TABLE public.offers ADD COLUMN IF NOT EXISTS source_url TEXT;
ALTER TABLE public.offers ADD COLUMN IF NOT EXISTS image_url TEXT;
ALTER TABLE public.offers ADD COLUMN IF NOT EXISTS traffic_restrictions TEXT NOT NULL DEFAULT '';
ALTER TABLE public.offers ADD COLUMN IF NOT EXISTS payment_model VARCHAR(30) NOT NULL DEFAULT 'CPA';
ALTER TABLE public.offers ADD COLUMN IF NOT EXISTS currency VARCHAR(8) NOT NULL DEFAULT 'USD';
ALTER TABLE public.offers ADD COLUMN IF NOT EXISTS payout_terms TEXT NOT NULL DEFAULT '';
ALTER TABLE public.offers ADD COLUMN IF NOT EXISTS status VARCHAR(16) NOT NULL DEFAULT 'draft';
ALTER TABLE public.offers ADD COLUMN IF NOT EXISTS display_order INTEGER NOT NULL DEFAULT 0;
ALTER TABLE public.offers ADD COLUMN IF NOT EXISTS commission_percent NUMERIC(5,2) NOT NULL DEFAULT 20;
ALTER TABLE public.offers ADD COLUMN IF NOT EXISTS hold_override_days INTEGER NOT NULL DEFAULT 10;
ALTER TABLE public.offers ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ NOT NULL DEFAULT now();
CREATE INDEX IF NOT EXISTS idx_cpa_offers_public ON public.offers(vertical_slug, status, display_order);
CREATE INDEX IF NOT EXISTS idx_cpa_offers_network ON public.offers(network_id);
